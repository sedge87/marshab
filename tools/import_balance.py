"""Turn docs/MarsHabitat_Balance.xlsx into data/resources.json for the game.

The spreadsheet is the place to tune every number the habitat simulation
uses (crew needs, room cargo, equipment power and outputs, site differences).
This script reads only its input cells, so it works whether or not the
workbook has been recalculated; worked-out cells (formulas) are ignored.

Usage:  python tools/import_balance.py [path/to/MarsHabitat_Balance.xlsx]
Needs:  pip install openpyxl
"""
import json
import sys
from pathlib import Path

from openpyxl import load_workbook

PROJECT = Path(__file__).resolve().parent.parent
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else PROJECT / "docs" / "MarsHabitat_Balance.xlsx"
OUT = PROJECT / "data" / "resources.json"

EQUIPMENT_FIELDS = ["cargo_kg", "power_kw", "hours_per_sol", None, "makes_power_kw", "o2_kg", "co2_kg", "water_l", "food_kg",
                    "stores_food_kg", "stores_water_l", "stores_o2_kg", "stores_kwh", "heat_kw", "berths", "research"]
SITE_FIELDS = {
    "Dust storms per 100 sols": "dust_storms_per_100_sols",
    "Storm cuts solar by": "storm_solar_cut",
    "Storm length (sols)": "storm_sols",
    "Landing cargo bonus": "cargo_bonus",
}


def number(value):
    """Input cells only: formulas (strings starting '=') are skipped."""
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return round(float(value), 4)
    return None


def main() -> None:
    wb = load_workbook(SOURCE)
    settings = {}
    for row in wb["Settings"].iter_rows(min_row=2):
        key, value = row[4].value, number(row[1].value)
        if key and value is not None:
            settings[str(key)] = value

    rooms = {}
    for row in wb["Rooms"].iter_rows(min_row=2):
        rid = row[0].value
        if not rid or number(row[2].value) is None or " " in str(rid):
            continue
        rooms[str(rid)] = {"cargo_kg_per_cell": number(row[2].value), "always_kw_per_cell": number(row[3].value),
                           "light_kw_per_cell": number(row[4].value), "target_c": number(row[5].value)}
    for row in wb["Rooms"].iter_rows(min_row=2):
        if str(row[0].value or "").startswith("Hull window"):
            settings["window_cargo_kg"] = number(row[2].value)

    equipment = {}
    for row in wb["Equipment"].iter_rows(min_row=2):
        iid = row[0].value
        if not iid or " " in str(iid):
            continue
        entry = {"room": str(row[2].value)}
        for field, cell in zip(EQUIPMENT_FIELDS, row[3:19]):
            if field is None:
                continue
            value = number(cell.value)
            if value:
                entry[field] = value
        equipment[str(iid)] = entry
    # Outputs kept on the Settings sheet (one place to edit them).
    equipment.setdefault("solar_array", {})["makes_power_kw"] = settings["solar_peak_kw"]
    equipment.setdefault("surface_reactor", {})["makes_power_kw"] = settings["reactor_kw"]
    equipment.setdefault("ice_drill", {})["water_l"] = settings["ice_drill_l"]
    equipment.setdefault("battery_bank", {})["stores_kwh"] = settings["battery_kwh"]

    sites = {}
    sheet = wb["Sites"]
    ids = [cell.value for cell in sheet[2][1:5]]
    for row in sheet.iter_rows(min_row=3):
        field = SITE_FIELDS.get(str(row[0].value))
        if not field:
            continue
        for site_id, cell in zip(ids, row[1:5]):
            sites.setdefault(str(site_id), {})[field] = number(cell.value)

    data = {"_comment": "Generated by tools/import_balance.py from docs/MarsHabitat_Balance.xlsx. Edit the spreadsheet, not this file.",
            "settings": settings, "rooms": rooms, "equipment": equipment, "sites": sites}
    OUT.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(PROJECT)}: {len(settings)} settings, {len(rooms)} rooms, {len(equipment)} items, {len(sites)} sites.")


if __name__ == "__main__":
    main()
